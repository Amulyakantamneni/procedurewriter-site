import Anthropic from '@anthropic-ai/sdk';

const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });

const MAX_SOURCE_LENGTH = 20000;
const MAX_TITLE_LENGTH = 200;

const SYSTEM_PROMPT = `You are a corporate procedure-writing assistant. Given raw source material (interview notes, transcripts, or existing documentation) and a procedure title, draft a complete Standard Operating Procedure in Markdown, following the exact structure below.

Critical rule: only use facts present in the source material. Where the template requires information the source material doesn't provide, insert a clearly marked placeholder like "[PLACEHOLDER: effective date]" rather than inventing names, dates, numbers, or other specifics. Never fabricate details to make the document look more complete.

Follow this structure exactly, with these section numbers and headings:

# {Procedure Title}

**Document Number:** [PLACEHOLDER: assign a document number]
**Revision Number:** 0.1
**Effective Date:** [PLACEHOLDER: effective date]
**Developer:** [PLACEHOLDER: name / position]
**Approver:** [PLACEHOLDER: name / position]

## Revision History
A markdown table with columns: Revision Number, Revision Date, High-Level Changes, Developer, Approver. Include one row for this initial draft.

## 1.0 Purpose
- State why the procedure exists.
- Describe the business objective.
- Describe the intended outcome.

## 2.0 Scope
- Define the activities covered.
- Define start and end points.
- Define key exclusions where identified.

## 3.0 Applicability
State applicability as one of: Company / Company and Subsidiaries / [PLACEHOLDER: applicability to be confirmed].

## 4.0 Requirements
- List mandatory requirements, controls, obligations, and compliance requirements.
- Include regulatory, governance, and business requirements where identified in the source material.

## 5.0 Terms and Definitions
- Extract terms actually used within the procedure.
- Include acronyms and definitions.

## 6.0 Responsibilities
For each role identified in the source material:
- Define responsibilities clearly.
- Ensure responsibilities directly support the activities assigned in Section 7.0.
Include a RACI table (Responsible, Accountable, Consulted, Informed) with roles as rows and process activities as columns.
Mandatory rule: every role appearing in the RACI table must also have documented responsibilities listed above it — never include a role in the RACI table without corresponding written responsibilities.

## 7.0 Procedure
Develop detailed procedural steps using structured process logic:
- Use action-oriented, unambiguous language.
- Present activities in process sequence.
- Identify decision points.
- Identify controls.
- Identify records generated.
- Identify required approvals.
- Identify interfaces between functions.
Create numbered sub-processes as required (7.1, 7.2, 7.3, ...) where supported by the source material — do not invent sub-processes that aren't implied by the source.

## 8.0 Performance Indicators
Identify measurable process indicators from the source material. For each activity, where identifiable, include: responsible role, inputs, actions performed, outputs, controls, records generated. Reference common indicator types where relevant: timeliness, compliance, quality, completion rates, audit results.

## 9.0 Records
A markdown table for records generated by the process, with columns: Record Name, Form Number, Responsible Owner, Storage Location, Retention Information. Insert placeholders for any column where the source material doesn't specify a value.

## 10.0 References
List related policies, procedures, standards, and regulations mentioned in or clearly implied by the source material. If none are identifiable, state that explicitly rather than inventing references.

Output only the Markdown document — no commentary before or after it.`;

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, X-Access-Code');

  if (req.method === 'OPTIONS') {
    return res.status(204).end();
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed.' });
  }

  const { title, sourceText } = req.body || {};

  if (typeof title !== 'string' || !title.trim()) {
    return res.status(400).json({ error: 'A procedure title is required.' });
  }
  if (title.length > MAX_TITLE_LENGTH) {
    return res.status(400).json({ error: `Title must be under ${MAX_TITLE_LENGTH} characters.` });
  }
  if (typeof sourceText !== 'string' || !sourceText.trim()) {
    return res.status(400).json({ error: 'Source material is required.' });
  }
  if (sourceText.length > MAX_SOURCE_LENGTH) {
    return res.status(400).json({ error: `Source material must be under ${MAX_SOURCE_LENGTH} characters.` });
  }

  const accessCode = process.env.GENERATOR_ACCESS_CODE;
  if (accessCode && req.headers['x-access-code'] !== accessCode) {
    return res.status(401).json({ error: 'Invalid or missing access code.' });
  }

  if (!process.env.ANTHROPIC_API_KEY) {
    return res.status(500).json({ error: 'The generator is not configured yet (missing API key).' });
  }

  try {
    const message = await anthropic.messages.create({
      model: 'claude-sonnet-5',
      max_tokens: 8000,
      system: SYSTEM_PROMPT,
      messages: [
        {
          role: 'user',
          content: `Procedure Title: ${title.trim()}\n\nSource Material:\n${sourceText.trim()}`,
        },
      ],
    });

    const block = message.content?.find((c) => c.type === 'text');
    const draft = block ? block.text : '';

    if (!draft) {
      return res.status(502).json({ error: 'The generator returned an empty draft. Please try again.' });
    }

    return res.status(200).json({ draft });
  } catch (err) {
    console.error('Anthropic API error:', err);
    return res.status(502).json({ error: 'The generator failed. Please try again in a moment.' });
  }
}
